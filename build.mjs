/**
 * Build droplets-dsh: host bundle (index.js, ESM, peers external) and client
 * bundle (client.js, window.__ModuleLoader__ CJS wrapper). Third-party deps
 * (fast-xml-parser, undici, ip-address, fflate, pdfjs-dist on the host;
 * d3-force, dompurify on the client) are bundled in; @deepseek-ai/* peers and
 * node/react builtins stay external.
 */
import { mkdirSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));

mkdirSync(join(here, 'locale'), { recursive: true });

// ---- host ------------------------------------------------------------------

await esbuild.build({
  entryPoints: [join(here, 'src/host/index.js')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  outfile: join(here, 'index.js'),
  external: ['@deepseek-ai/*', 'node:*'],
  sourcemap: false,
  logLevel: 'info',
  legalComments: 'none',
  banner: {
    js: [
      '/* droplets-dsh · host bundle (generated by build.mjs; do not edit) */',
      'import { createRequire as __createRequire } from "node:module";',
      'const require = __createRequire(import.meta.url);',
    ].join('\n'),
  },
});

// ---- client ----------------------------------------------------------------

const banner = `window.__ModuleLoader__.load({
\tid: "droplets-dsh",
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
`;
const footer = `
\t\treturn module.exports;
\t}
});
`;

await esbuild.build({
  entryPoints: [join(here, 'src/client/index.jsx')],
  loader: { '.css': 'text', '.json': 'json' },
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'chrome120',
  jsx: 'automatic',
  jsxImportSource: 'react',
  outfile: join(here, 'client.js'),
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client', '@deepseek-ai/*'],
  sourcemap: false,
  logLevel: 'info',
  legalComments: 'none',
  minify: false,
  banner: { js: banner },
  footer: { js: footer },
});

const hostSize = statSync(join(here, 'index.js')).size;
const clientSize = statSync(join(here, 'client.js')).size;
console.log(`host   index.js  ${(hostSize / 1024).toFixed(1)} KB`);
console.log(`client client.js ${(clientSize / 1024).toFixed(1)} KB`);
